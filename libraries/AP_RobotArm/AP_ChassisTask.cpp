// 位置生成函数 - 基于预定义轨迹
float generate_position(MIT_Motor::MotorInstance* motor) {
    if (motor == nullptr || current_point >= total_points) {
        return 0.0f;
    }
    
    // 根据电机ID返回对应的关节角度
    uint8_t joint_index = motor->motor_id - 1; // 转换为0-5索引
    if (joint_index >= 6) {
        return 0.0f;
    }
    
    float position = predefined_joints[current_point][joint_index];
    
    // 更新轨迹点（只在第一个电机时更新，避免重复）
    if (joint_index == 0) {
        current_point = (current_point + 1) % total_points;
    }
    
    return position;
}

// ArduPilot兼容的主任务函数 - 简化实现
void chassis_task(void const* pvParameters) {
    // ArduPilot中任务管理由调度器处理
    // 这里提供一个简单的初始化和状态报告
    GCS_SEND_TEXT(MAV_SEVERITY_INFO, "ChassisTask: Task started in ArduPilot mode");
    
    // 重置轨迹点
    current_point = 0;
    
    GCS_SEND_TEXT(MAV_SEVERITY_INFO, "ChassisTask: Trajectory initialized with %u points", 
                  (unsigned)total_points);
}





